#
#   P(最差情景) = P(环节1) × P(环节2..5 全部到位 | 环节1发生)
#   P(单年巨亏) = P(环节1) × P(违约 | 环节1发生) + P(局部违约 | 周期未崩)
#
# 环节1 的概率分五档给出（依据见报告第二节与第六节的在手证据）；
# 环节2-5 的概率是在"环节1已发生"这一前提下的条件概率。
