"""概率模型修正：五环节不是独立事件。

关键建模错误：把五个环节当独立事件相乘，得到 0.1%。
事实：环节 2、3、4、5 大部分是环节 1（AI 资本开支周期见顶并多年下行）的
      条件结果。需求崩塌会同时导致：大客户自研加速器加速替代（份额下降）、
      定价权丧失与产能过剩（净利率下降）、非数据中心业务萎缩、担保与承诺被兑现。
      它们是同一条因果链的下游，不是五个独立的硬币。

修正后的结构：
  P(最差情景) = P(环节1) × P(其余环节全部到位 | 环节1发生)
  单年巨亏     = P(环节1) × P(违约 | 环节1发生) + P(违约 | 环节1未发生但局部违约)

这里 P(环节1) 才是真正需要判断的量，而它有直接的在手证据约束。
"""
from decimal import Decimal as D

print("=" * 94)
print("修正后的概率结构")
print("=" * 94)

print("""
环节 1  AI 资本开支周期见顶并进入多年下行（2036 价值池回到 6000 亿）
   ↓ 条件因果（非独立）
   ├─ 环节 2  份额降到 15%：客户自研 ASIC 与替代方案加速渗透，
   │          但英伟达仍保有系统/软件/交付优势，不会归零 → 份额区间 10%-25%
   ├─ 环节 3  净利率压到 8%：产能过剩 + 定价权下降 + 高固定成本摊薄不足
   │          → 净利率区间 6%-15%（此为条件概率，不是无条件概率）
   ├─ 环节 4  其他收入萎缩到 300 亿：几乎必然跟随 → 条件概率 70%-90%
   └─ 环节 5  担保与承诺被兑现：需要具体的违约事件，不是周期的必然结果
              → 条件概率 25%-45%（有 OpenAI 单一承租方绑定，但租约期 20 年）
""")

# 环节 1 的概率：分情景给出
print("=" * 94)
print("环节 1 的概率：AI 资本开支周期见顶并多年下行")
print("=" * 94)
print("""
支持发生的证据（提高概率）：
  · 高盛测算 2026 年五家超大规模厂商 AI 基建开支 8000 亿，AI 云收入仅高出
    趋势线 700 亿，每年 2300 亿缺口，需约 3000 亿年收入才能打平
  · 生态要获得稳健回报需 AI 软件年支出约 1 万亿美元，远超当前规模
  · 微软已把 FY2026 资本开支指引从 1750 亿下调至 1700 亿；Alphabet 当季 FCF 为负超 90 亿
  · Gartner：2030 年 80% 新云将被并购或停运

反对发生的证据（压低概率）：
  · 五家主要买方资本开支合计同比 +77.6%（SEC XBRL 一手）
  · 高盛预测 2027 年升至 1.2 万亿、2028 年 1.4 万亿
  · 微软 CFO 明确：2027 上半年资本开支将加速；明年超大规模厂商合计超 1 万亿美元
  · 资本开支由少数几家的投资决策驱动，可在任一时点集体下调，也可同样快速上调
  · 电力供应、存储供应、数据中心选址是硬约束，限制下行速度也限制上行
""")

p1 = {
    "极乐观（周期再延续十年）": 0.05,
    "乐观（2030 前后温和回落，2036 池 1.2-1.5 万亿）": 0.25,
    "中性（2028-2030 见顶，多年下行但池回到 6000-9000 亿）": 0.45,
    "悲观（2027 见顶，池回到 3000-6000 亿）": 0.20,
    "极悲观（2027 即崩盘，池低于 3000 亿）": 0.05,
}
print("环节 1 概率分布（作者判断，依据如上）：")
for k, v in p1.items():
    print(f"  {k:<44} {v:>6.0%}")

# 条件概率
cond = {
    "环节2_份额降到15%": (0.30, 0.60),
    "环节3_净利率压到8%": (0.25, 0.50),
    "环节4_其他收入萎缩": (0.70, 0.90),
    "环节5_资产负债表被兑现": (0.25, 0.45),
}

print("\n" + "=" * 94)
print("给定环节 1 发生，各下游环节的条件概率")
print("=" * 94)
for k, (lo, hi) in cond.items():
    print(f"  {k:<26} {lo:>5.0%} - {hi:>3.0%}")

print("\n" + "=" * 94)
print("联合概率：P(环节1) × P(下游全部到位 | 环节1)")
print("=" * 94)
print(f"{'环节1情景':<40}{'P(环节1)':>10}{'×下游乘积':>12}{'= 最差情景':>12}{'×违约条件':>12}{'= 含巨亏':>12}")

for name, p1v in p1.items():
    # 下游乘积：取条件概率区间中值（保守）与下界
    mid_prod = D(1)
    lo_prod = D(1)
    for lo, hi in cond.values():
        mid_prod *= D(str((lo + hi) / 2))
        lo_prod *= D(str(lo))
    p_worst = D(str(p1v)) * mid_prod
    p_worst_lo = D(str(p1v)) * lo_prod
    # 含巨亏：P(环节1)*P(环节5|1) + P(违约但周期未崩)
    p_giant = D(str(p1v)) * D(str(sum(cond["环节5_资产负债表被兑现"]) / 2)) + D("0.03")
    print(f"{name:<40}{p1v:>9.0%}{float(mid_prod):>11.1%}{float(p_worst):>11.2%}"
          f"{float(D(str(p1v))*D(str(sum(cond['环节5_资产负债表被兑现'])/2))):>11.2%}{float(p_giant):>11.1%}")

print("\n" + "=" * 94)
print("加总：最差情景（2036 净利 96 亿）与路径中单年巨亏")
print("=" * 94)
tot_worst = sum(D(str(v)) for v in p1.values())
# 用各情景下的最差情景概率加总（需再乘下游条件概率，此处用中性下界的 P(1)=0.45 档）
# 保守做法：取各环节 1 档位下"最差情景"概率的加权和
worst_sum = D("0")
for name, p1v in p1.items():
    mid_prod = D(1)
    for lo, hi in cond.values():
        mid_prod *= D(str((lo + hi) / 2))
    worst_sum += D(str(p1v)) * mid_prod
giant_sum = D("0")
for name, p1v in p1.items():
    giant_sum += D(str(p1v)) * D(str(sum(cond["环节5_资产负债表被兑现"]) / 2))
giant_sum += D("0.03")
print(f"  最差情景（2036 净利 96 亿）总概率 ≈ {float(worst_sum)*100:.1f}%")
print(f"  含单年巨亏（路径中断）总概率 ≈ {float(giant_sum)*100:.1f}%")
print()
print("  敏感性：下游条件概率取区间下界时")
worst_lo = sum(D(str(v)) for v in p1.values()) * D(1)
lo_prod = D(1)
for lo, hi in cond.values():
    lo_prod *= D(str(lo))
worst_lo = D(0)
for name, p1v in p1.items():
    worst_lo += D(str(p1v)) * lo_prod
print(f"    最差情景 ≈ {float(worst_lo)*100:.1f}%")
print("  敏感性：下游条件概率取区间上界时")
hi_prod = D(1)
for lo, hi in cond.values():
    hi_prod *= D(str(hi))
worst_hi = D(0)
for name, p1v in p1.items():
    worst_hi += D(str(p1v)) * hi_prod
print(f"    最差情景 ≈ {float(worst_hi)*100:.1f}%")
